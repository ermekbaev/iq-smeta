import { describe, it, expect } from "vitest";
import { autoSubject } from "./subject";

describe("autoSubject — профессиональный предмет КП из направлений", () => {
  it("одно направление → своя формулировка", () => {
    expect(autoSubject(["Полив"])).toBe("на устройство системы автоматического полива");
    expect(autoSubject(["Дренаж"])).toBe("на монтаж дренажной системы");
    expect(autoSubject(["Газон"])).toBe("на укладку рулонного газона");
    expect(autoSubject(["Освещение"])).toBe("на устройство системы ландшафтного освещения");
  });

  it("«Свет» и «Освещение» → одна формулировка, дублей нет", () => {
    expect(autoSubject(["Свет", "Освещение"])).toBe(
      "на устройство системы ландшафтного освещения"
    );
  });

  it("два направления → через «и»", () => {
    expect(autoSubject(["Полив", "Дренаж"])).toBe(
      "на устройство системы автоматического полива и монтаж дренажной системы"
    );
  });

  it("три и больше → обобщённая формулировка", () => {
    expect(autoSubject(["Полив", "Дренаж", "Освещение", "Террасы"])).toBe(
      "на комплекс работ по благоустройству"
    );
  });

  it("служебные разделы игнорируются", () => {
    expect(autoSubject(["Полив", "Прочее", "Работы", "Доставка", "Материалы"])).toBe(
      "на устройство системы автоматического полива"
    );
  });

  it("категории не из списка → комплекс работ (не сырые слова)", () => {
    expect(autoSubject(["Прочее"])).toBe("");
    expect(autoSubject([])).toBe("");
  });

  it("не выводит сырой список категорий (баг, который правим)", () => {
    const s = autoSubject(["Полив", "Дренаж", "Освещение", "Террасы"]);
    expect(s).not.toContain("полив,");
    expect(s).not.toContain("по устройству:");
  });
});
