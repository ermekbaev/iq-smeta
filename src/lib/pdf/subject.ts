// Предмет КП («Коммерческое предложение НА …») из направлений сметы.
// Не дословный перенос слов и не список категорий, а профессиональная
// формулировка по шаблонам — так просил заказчик (надёжнее ИИ-генерации).

// Служебные разделы — не вид работ, в предмет не идут.
const GENERIC_CATEGORY = /^(прочее|работы|материалы|оборудование|услуги|доставка)$/i;

// Направление (категория прайса) → профессиональная формулировка (винительный
// падеж, чтобы вставало после «на»: «на устройство …», «на монтаж …»).
const SUBJECT_TEMPLATES: Record<string, string> = {
  "полив": "устройство системы автоматического полива",
  "дренаж": "монтаж дренажной системы",
  "газон": "укладку рулонного газона",
  "освещение": "устройство системы ландшафтного освещения",
  "свет": "устройство системы ландшафтного освещения",
  "мощение": "устройство мощения дорожек и площадок",
  "фундаменты": "устройство бетонных фундаментов",
  "террасы": "устройство террасы",
  "резиновые покрытия": "устройство резиновых покрытий",
  "благоустройство": "комплексное благоустройство территории",
};

/**
 * Формирует предмет КП из направлений сметы.
 * Одно направление → его формулировка; два → через «и»; три и больше или
 * незнакомые категории → «на комплекс работ по благоустройству».
 * Возвращает строку вида «на устройство системы автоматического полива»
 * (или "" — тогда в КП останется просто «Коммерческое предложение»).
 */
export function autoSubject(categories: string[]): string {
  const uniq = [
    ...new Set(
      categories.map((c) => c.trim().toLowerCase()).filter((c) => c && !GENERIC_CATEGORY.test(c))
    ),
  ];
  if (uniq.length === 0) return "";

  const phrases = [...new Set(uniq.map((c) => SUBJECT_TEMPLATES[c]).filter(Boolean))];

  // есть незнакомые направления или их много — обобщаем
  const hasUnknown = phrases.length < uniq.length;
  if (phrases.length === 0) return "на комплекс работ по благоустройству";
  if (phrases.length >= 3 || (hasUnknown && phrases.length >= 2)) {
    return "на комплекс работ по благоустройству";
  }
  if (phrases.length === 2) return `на ${phrases[0]} и ${phrases[1]}`;
  return `на ${phrases[0]}`;
}
